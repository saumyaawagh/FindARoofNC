"""Step 08: short AI-written briefs for every county and scored Durham tract.

Facts in, prose out:
  1. Python builds a small `facts` dict from the computed index (no raw data goes to the model).
  2. Python picks 2–3 prevention actions from a fixed playbook (the model never chooses them).
  3. Google's Gemini writes the prose, as JSON, using pipeline/prompts/brief_prompt.txt.
  4. Every number in the reply must appear in the facts (allowing rounding), and the action
     keys must match. Up to 2 retries; after that a template brief built only from facts is used.
Briefs are cached by a hash of their facts, so unchanged units aren't regenerated.

Writes site/src/data/briefs.json.

Run with --template-only to skip the API: every brief that needs generating gets the template
version, marked as a fallback, so it is regenerated by the model on the next normal run.
"""
import argparse
import hashlib
import json
import os
import re
import threading
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone

from pydantic import BaseModel

import config
import helpers  # noqa: F401  (loads .env)

PROMPT_FILE = config.PIPELINE / "prompts" / "brief_prompt.txt"
OUTPUT = config.SITE_DATA / "briefs.json"
DEFAULT_MODEL = "gemini-3.8-flash"  # used when LLM_MODEL in .env is empty
TEMPERATURE = 0.2  # low, so briefs stay close to the facts and consistent between runs (spec §8)
MAX_RETRIES = 2  # extra attempts when a reply fails the number check
WORKERS = 4  # requests in flight at once; kept low for Gemini's per-minute rate limits
RATE_LIMIT_WAITS = [10, 30, 60, 120]  # seconds to wait after "too many requests" / server errors
TRACT_NO_CHANGE = "Change data is not available at tract level."

# The fixed action playbook (spec §8). Python picks; the model only explains why.
ACTION_LABELS = {
    "eviction_diversion": "Eviction diversion/mediation",
    "tenant_legal_aid": "Tenant legal aid",
    "foreclosure_counseling": "Foreclosure prevention counseling",
    "emergency_rental_assistance": "Emergency rental assistance",
    "housing_navigation_vouchers": "Housing navigation & vouchers",
    "landlord_mediation": "Landlord mediation",
    "workforce_services": "Workforce & re-employment services",
    "utility_assistance": "Utility assistance",
}
PLAYBOOK = {
    "A": ["eviction_diversion", "tenant_legal_aid", "foreclosure_counseling"],
    "B": ["emergency_rental_assistance", "housing_navigation_vouchers", "landlord_mediation"],
    "C": ["workforce_services", "emergency_rental_assistance", "utility_assistance"],
    "D": ["housing_navigation_vouchers", "utility_assistance"],  # structural vulnerability
}

class GeminiStopped(Exception):
    """Gemini won't accept more requests for now (daily quota used up, or no billing credit).
    Retrying in a few minutes won't help, so the run stops calling the API."""


# The shape the model must return. Gemini's structured output fills exactly these fields.
class Action(BaseModel):
    key: str
    label: str
    why: str


class Brief(BaseModel):
    headline: str
    situation: str
    drivers: list[str]
    whats_changed: str
    actions: list[Action]
    caveat: str


# ---------------------------------------------------------------------------
# Facts and actions (all decided in Python)
# ---------------------------------------------------------------------------
def build_facts(unit, kind, total):
    pillars = {config.PILLARS[k]["label"]: (None if p is None else round(p["score"]))
               for k, p in unit["pillars"].items()}
    facts = {
        "name": f"{unit['name']} County" if kind == "county" else f"{unit['name']}, Durham County",
        "geography": kind,
        "compared_with": "all 100 NC counties" if kind == "county" else "other Durham County census tracts",
        "score": round(unit["score"]),
        "score_scale": "0 to 100, higher means more housing-loss pressure",
        "tier": unit["tier"],
        "rank": unit["rank"],
        "rank_out_of": total,
        "top_driver_sentences": [d["sentence"] for d in unit["top_drivers"]],
        "pillar_scores": pillars,
    }
    if kind == "county":
        change = unit["indicators"]["unemployment_change"]
        facts.update({
            "momentum_score": round(unit["momentum"]),
            "momentum_tier": unit["momentum_tier"],
            "rising_flag": unit["rising"],
            "rising_rule": "Rising = momentum 75 or higher and score 40 or higher",
            "unemployment_change_points": round(change["value"], 1),
            "unemployment_change_period": change["vintage"],
        })
    return facts


def choose_actions(unit):
    """Actions for the highest-scoring pillar (ties: the pillar listed first)."""
    scored = {k: p["score"] for k, p in unit["pillars"].items() if p is not None}
    top = max(scored, key=lambda k: (scored[k], -list(config.PILLARS).index(k)))
    keys = list(PLAYBOOK[top])
    if top == "A":
        # Foreclosure counseling only where foreclosure filings are notably high.
        pct = unit["indicators"].get("foreclosure_rate", {}).get("pct")
        if pct is None or pct < 70:
            keys.remove("foreclosure_counseling")
    return [{"key": k, "label": ACTION_LABELS[k]} for k in keys]


def facts_hash(facts, actions, model, prompt):
    blob = json.dumps({"facts": facts, "actions": actions, "model": model, "prompt": prompt}, sort_keys=True)
    return hashlib.sha256(blob.encode()).hexdigest()[:16]


# ---------------------------------------------------------------------------
# Number check
# ---------------------------------------------------------------------------
# A number token: optional sign, digits with optional thousands commas and decimals.
# The look-behind stops "2025-26" from being read as 2025 and -26.
NUMBER = re.compile(r"(?<![\w.])[-+−]?\d[\d,]*(?:\.\d+)?")


def numbers_in(text):
    out = []
    for token in NUMBER.findall(text):
        token = token.replace(",", "").replace("−", "-").rstrip(".")
        try:
            out.append(float(token))
        except ValueError:
            pass
    return out


def allowed_numbers(facts):
    """Every number in the facts, plus its rounded forms and size without a sign."""
    values = []

    def walk(x):
        if isinstance(x, bool) or x is None:
            return
        if isinstance(x, (int, float)):
            values.append(float(x))
        elif isinstance(x, str):
            values.extend(numbers_in(x))
        elif isinstance(x, dict):
            for v in x.values():
                walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)

    walk(facts)
    allowed = set()
    for v in values:
        # "−0.4 points" may be written as "fell 0.4 points", so the size alone is allowed too.
        for w in (v, abs(v)):
            allowed.update({round(w, 6), round(w, 1), float(round(w))})
    return allowed


def check_brief(brief, facts, actions, kind):
    """Return a list of problems; an empty list means the brief passes."""
    problems = []
    allowed = allowed_numbers(facts)
    texts = [brief["headline"], brief["situation"], brief["whats_changed"], brief["caveat"],
             *brief["drivers"], *(a["why"] for a in brief["actions"]), *(a["label"] for a in brief["actions"])]
    for text in texts:
        for n in numbers_in(text):
            if round(n, 6) not in allowed:
                problems.append(f"number {n:g} is not in the facts: {text!r}")
    if [a["key"] for a in brief["actions"]] != [a["key"] for a in actions]:
        problems.append(f"action keys {[a['key'] for a in brief['actions']]} != {[a['key'] for a in actions]}")
    if len(brief["drivers"]) != len(facts["top_driver_sentences"]):
        problems.append(f"{len(brief['drivers'])} driver bullets, expected {len(facts['top_driver_sentences'])}")
    if len(brief["headline"].split()) > 12:
        problems.append("headline longer than 12 words")
    if kind == "tract" and brief["whats_changed"].strip() != TRACT_NO_CHANGE:
        problems.append("tract whats_changed must be the fixed sentence")
    return problems


# ---------------------------------------------------------------------------
# Template fallback (facts only, no AI)
# ---------------------------------------------------------------------------
def template_brief(facts, actions, kind):
    name, score, tier = facts["name"], facts["score"], facts["tier"]
    top_pillar = max((k for k, v in facts["pillar_scores"].items() if v is not None),
                     key=lambda k: facts["pillar_scores"][k])
    if kind == "county":
        changed = (f"Its Momentum score is {facts['momentum_score']} ({facts['momentum_tier']})"
                   + (", so it is flagged as Rising." if facts["rising_flag"] else "."))
    else:
        changed = TRACT_NO_CHANGE
    return {
        # Tracts use the short "Tract 3.01" form: long neighborhood names could push the headline
        # past 12 words, and the full name is already the panel's title.
        "headline": f"{name.split(' · ')[0] if kind == 'tract' else name}: {tier} housing-loss pressure",
        "situation": (f"{name} has a Risk Score of {score} ({tier}), rank {facts['rank']} "
                      f"of {facts['rank_out_of']}. Scores compare it with {facts['compared_with']}."),
        "drivers": facts["top_driver_sentences"],
        "whats_changed": changed,
        "actions": [{**a, "why": f"Its highest-scoring pressure area is {top_pillar.lower()}."} for a in actions],
        "caveat": "This is an area-level signal, not a prediction about any household.",
    }


# ---------------------------------------------------------------------------
# Model call
# ---------------------------------------------------------------------------
def ask_model(client, model, prompt_text):
    """One request to Gemini. Returns (brief dict or None, problem string or None)."""
    from google.genai import errors, types

    config_ = types.GenerateContentConfig(
        temperature=TEMPERATURE,
        response_mime_type="application/json",
        response_schema=Brief,
        # Short, tightly constrained writing: little reasoning needed, and it's much faster.
        thinking_config=types.ThinkingConfig(thinking_level=types.ThinkingLevel.LOW),
    )
    # Wait and try again on rate limits (429) and temporary server errors (5xx).
    for wait in [*RATE_LIMIT_WAITS, None]:
        try:
            response = client.models.generate_content(model=model, contents=prompt_text, config=config_)
            break
        except errors.APIError as err:
            # A per-day quota (the free tier allows ~20 requests a day per model) resets hours
            # later, and 402 means the project's prepaid credit is used up: stop, don't retry.
            if err.code == 402 or (err.code == 429 and "PerDay" in str(err)):
                raise GeminiStopped(f"{err.code}: {str(err.message)[:160]}") from err
            if wait is None or not (err.code == 429 or (err.code or 0) >= 500):
                raise
            time.sleep(wait)

    if response.parsed is None:
        reason = response.candidates[0].finish_reason if response.candidates else "no candidates"
        return None, f"no usable reply (finish_reason={reason})"
    return response.parsed.model_dump(), None


def generate(client, model, prompt, unit_id, facts, actions, kind):
    prompt_text = (prompt.replace("{facts_json}", json.dumps(facts, indent=2, ensure_ascii=False))
                   .replace("{actions_json}", json.dumps(actions, indent=2)))
    problems = []
    for attempt in range(1 + MAX_RETRIES):
        brief, error = ask_model(client, model, prompt_text)
        problems = [error] if error else check_brief(brief, facts, actions, kind)
        if not problems:
            return brief, attempt, None
    return None, MAX_RETRIES, problems


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--template-only", action="store_true",
                        help="don't call the API; use template briefs (marked fallback) for anything not cached")
    template_only = parser.parse_args().template_only

    prompt = PROMPT_FILE.read_text()
    model = os.getenv("LLM_MODEL", "").strip() or DEFAULT_MODEL

    counties = json.loads((config.INTERIM / "index_counties.json").read_text())
    tracts = json.loads((config.INTERIM / "index_tracts.json").read_text())
    scored_tracts = [t for t in tracts if t["score"] is not None]

    jobs = []
    for unit in counties:
        jobs.append((unit["fips"], unit, "county", len(counties)))
    for unit in scored_tracts:
        jobs.append((unit["geoid"], unit, "tract", len(scored_tracts)))

    cache = json.loads(OUTPUT.read_text()) if OUTPUT.exists() else {}
    results, todo = {}, []
    for unit_id, unit, kind, total in jobs:
        facts = build_facts(unit, kind, total)
        actions = choose_actions(unit)
        h = facts_hash(facts, actions, model, prompt)
        old = cache.get(unit_id)
        if old and old.get("facts_hash") == h and not old.get("fallback"):
            results[unit_id] = old
        else:
            todo.append((unit_id, facts, actions, kind, h))

    print(f"Model: {model}. Briefs needed: {len(jobs)}; cached: {len(results)}; to generate: {len(todo)}.")
    counts = {"generated": 0, "cached": len(results), "retried": 0, "fallback": 0}

    if todo and template_only:
        now = datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
        for unit_id, facts, actions, kind, h in todo:
            brief = template_brief(facts, actions, kind)
            results[unit_id] = {**brief, "model": "template", "fallback": True, "generated_at": now, "facts_hash": h}
        counts["fallback"] = len(todo)
        print("Template-only run: no API calls made.")
    elif todo:
        from google import genai
        from google.genai import errors

        key = os.getenv("GEMINI_API_KEY", "").strip()
        if not key:
            raise SystemExit("GEMINI_API_KEY is empty in .env. Add it, or run "
                             "08_briefs.py --template-only to use template briefs for now.")
        client = genai.Client(api_key=key)

        quota_hit = threading.Event()

        def run(job):
            unit_id, facts, actions, kind, h = job
            if quota_hit.is_set():
                return unit_id, facts, actions, kind, h, None, 0, ["skipped: daily quota reached"]
            try:
                brief, retries, problems = generate(client, model, prompt, unit_id, facts, actions, kind)
            except GeminiStopped as err:
                quota_hit.set()
                brief, retries, problems = None, 0, [f"Gemini stopped: {err}"]
            except (errors.APIError, json.JSONDecodeError, OSError) as err:
                brief, retries, problems = None, 0, [f"{type(err).__name__}: {err}"]
            return unit_id, facts, actions, kind, h, brief, retries, problems

        # Units are in rank order, so a limited quota goes to the highest-pressure places first.
        # Briefs not done yet keep a template until they are generated.
        for unit_id, facts, actions, kind, h in todo:
            if unit_id not in results:
                results[unit_id] = {**template_brief(facts, actions, kind), "model": "template",
                                    "fallback": True, "generated_at": None, "facts_hash": h}

        with ThreadPoolExecutor(max_workers=WORKERS) as pool:
            futures = [pool.submit(run, job) for job in todo]
            for future in as_completed(futures):
                unit_id, facts, actions, kind, h, brief, retries, problems = future.result()
                now = datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
                if brief is None:
                    if not problems[0].startswith("skipped"):
                        print(f"  FALLBACK {unit_id} ({facts['name']}): {problems[0][:160]}")
                    entry = {**template_brief(facts, actions, kind), "model": "template", "fallback": True}
                    counts["fallback"] += 1
                else:
                    entry = {**brief, "model": model, "fallback": False}
                    counts["generated"] += 1
                    counts["retried"] += retries > 0
                results[unit_id] = {**entry, "generated_at": now, "facts_hash": h}
                # Save after every brief, so an interruption never loses finished AI briefs.
                OUTPUT.write_text(json.dumps(results, separators=(",", ":"), ensure_ascii=False))

        if quota_hit.is_set():
            print(f"Gemini stopped accepting requests (daily quota or billing credit). {counts['fallback']} units "
                  f"keep a template brief for now; run this step again once that is resolved to fill them in.")

    OUTPUT.write_text(json.dumps(results, separators=(",", ":"), ensure_ascii=False))
    print(f"Briefs: generated {counts['generated']} / cached {counts['cached']} / "
          f"retried {counts['retried']} / fallback {counts['fallback']}. Wrote {OUTPUT.name}.")


if __name__ == "__main__":
    main()
